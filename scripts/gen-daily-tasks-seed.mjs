// Generates the Challenge 6.0 «Kunlik vazifalar» go-live seed (Daily Tasks PR-8, migration
// 20260930203000_challenge_daily_tasks_go_live.sql) with the ADMIN IMPORTER'S OWN CODE: parsePlan() +
// buildImportRows() from src/lib/dailyTasksPlan.ts, i.e. exactly the items the «Rejani import qilish» dialog
// (src/components/admin/ChallengePlanImportDialog.tsx) would send to admin_challenge_tasks_import().
//
//   node scripts/gen-daily-tasks-seed.mjs [plan.json]                 prints the seed block (one item per line)
//   node scripts/gen-daily-tasks-seed.mjs [plan.json] --check <file>   exits 1 unless <file> embeds exactly that block
//
// The plan defaults to src/lib/__fixtures__/challenge6-daily-tasks-plan.json (the owner-approved v2 plan's importer
// fields: title_uz, task_uz, learn_uz, submit_uz, type, points, format, auto_check, minutes). Node >= 22.18 / 24 loads
// the .ts module natively (type stripping); dailyTasksPlan.ts is dependency-free on purpose.
//
// The importer's inputs, fixed here as the migration asserts them live:
//   startDate      2026-10-05 (Monday)     weekdays [1..5] (platform_settings.challenge_tasks.task_weekdays)
//   occupiedDates  {}  existingRefs  {}    (production had no challenge_tasks row when this was generated; the
//                                           migration itself skips a date / plan_ref that is taken by then)
//   defaultPoints  {general: 5, instagram: 8}  (points is stored only when it differs -> null for every plan task;
//                                           the migration refuses to run if the live defaults differ)
// And the calendar rule the owner approved: week N day D -> the D-th weekday of week N, 2026-10-05 .. 2026-11-06.
import { readFileSync } from "node:fs";
import { addDays, buildImportRows, parsePlan, planRef } from "../src/lib/dailyTasksPlan.ts";

export const SEED_START = "2026-10-05";
export const SEED_WEEKDAYS = [1, 2, 3, 4, 5];
export const SEED_DEFAULT_POINTS = { general: 5, instagram: 8 };
export const BEGIN_MARK = "-- ▼ SEED ITEMS (generated by scripts/gen-daily-tasks-seed.mjs; do not edit by hand) ▼";
export const END_MARK = "-- ▲ SEED ITEMS ▲";

export function seedItems(planText) {
  const { tasks, errors } = parsePlan(planText);
  if (errors.length > 0) throw new Error(`plan does not parse: ${errors.join("; ")}`);
  if (tasks.length !== 25) throw new Error(`plan has ${tasks.length} tasks, expected 25`);
  const rows = buildImportRows(tasks, {
    startDate: SEED_START, weekdays: SEED_WEEKDAYS, occupiedDates: new Set(), existingRefs: new Set(),
    defaultPoints: SEED_DEFAULT_POINTS,
  });
  return rows.map((r) => {
    if (r.status !== "new" || !r.item) throw new Error(`${r.ref}: ${r.status} ${r.problems.join("; ")}`);
    const want = addDays(SEED_START, 7 * (r.task.week - 1) + (r.task.day - 1));
    if (r.task.day < 1 || r.task.day > 5 || r.item.task_date !== want) {
      throw new Error(`${planRef(r.task)}: date ${r.item.task_date}, expected ${want} (week N day D = the D-th weekday of week N)`);
    }
    return r.item;
  });
}

/** The literal the migration embeds: a JSON array, one item per line. */
export function seedBlock(items) {
  return "[\n" + items.map((it) => "  " + JSON.stringify(it)).join(",\n") + "\n]";
}

function main(argv) {
  const args = argv.slice(2);
  const ci = args.indexOf("--check");
  const checkFile = ci >= 0 ? args[ci + 1] : null;
  const planPath = args.find((a, i) => !a.startsWith("--") && (ci < 0 || i !== ci + 1))
    ?? "src/lib/__fixtures__/challenge6-daily-tasks-plan.json";
  const block = seedBlock(seedItems(readFileSync(planPath, "utf8")));
  if (!checkFile) {
    process.stdout.write(block + "\n");
    return 0;
  }
  const text = readFileSync(checkFile, "utf8").replace(/\r\n/g, "\n");
  const a = text.indexOf(BEGIN_MARK), b = text.indexOf(END_MARK);
  if (a < 0 || b < a) {
    console.error(`${checkFile}: seed markers not found`);
    return 1;
  }
  const inner = text.slice(a + BEGIN_MARK.length, b);
  const m = /\$seed\$([\s\S]*)\$seed\$/.exec(inner);
  if (!m || m[1].trim() !== block.trim()) {
    console.error(`${checkFile}: the embedded seed is NOT what the importer produces from ${planPath}`);
    return 1;
  }
  console.log(`${checkFile}: the embedded seed is exactly the importer's output for ${planPath} (25 items)`);
  return 0;
}

// Run as a script under Node only (the PGlite harness imports seedItems / seedBlock from Deno).
if (typeof globalThis.Deno === "undefined" &&
    String(process.argv[1] ?? "").replace(/\\/g, "/").endsWith("/gen-daily-tasks-seed.mjs")) {
  process.exitCode = main(process.argv);
}
