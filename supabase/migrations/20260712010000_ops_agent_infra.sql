-- 2) Vault accessor for the GitHub PAT used by repository_dispatch (Phase 4) and the
--    Telegram approve->merge flow (Phase 2). The secret itself is inserted by the OWNER via
--    the SQL editor (vault.create_secret('<PAT>', 'OPS_GITHUB_PAT', ...)) — never committed.
--    Accessor returns NULL until then; callers must treat NULL as "ops disabled".
create or replace function public.ops_github_pat()
returns text language sql stable security definer
set search_path = public, vault
as $fn$
  select decrypted_secret
  from vault.decrypted_secrets
  where name = 'OPS_GITHUB_PAT'
  order by created_at desc
  limit 1;
$fn$;
revoke execute on function public.ops_github_pat() from public, anon, authenticated;
grant execute on function public.ops_github_pat() to service_role;

